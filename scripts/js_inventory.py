#!/usr/bin/env python3
"""Writes docs/js-dependencies.md from editor/package-lock.json: every JavaScript package that is part of the
browser bundle (static/editor.js) or of its build, with version and license. `make js-inventory`; the lockfile is the
source of truth, so run it whenever the lockfile changes (a test in CI compares the file with the lockfile)."""
import json, pathlib, sys

root = pathlib.Path(__file__).resolve().parent.parent
lock = json.loads((root / "editor/package-lock.json").read_text())
direct = json.loads((root / "editor/package.json").read_text())
pk = {k.removeprefix("node_modules/"): v for k, v in lock["packages"].items() if k}
runtime = sorted((n, v) for n, v in pk.items() if not v.get("dev") and not v.get("optional"))
build = sorted((n, v) for n, v in pk.items() if v.get("dev") or v.get("optional"))
top = set(direct.get("dependencies", {})) | set(direct.get("devDependencies", {}))

def row(n, v):
    return f"| `{n}` | {v['version']} | {v.get('license', '?')} | {'direct' if n in top else 'indirect'} |"

out = [
    "# JavaScript dependencies", "",
    "<!-- generated by scripts/js_inventory.py from editor/package-lock.json: do not edit by hand -->", "",
    "Everything JavaScript that is not our own code. The live editor in the browser is a single file, `static/editor.js`, built from",
    "`editor/` with esbuild (`make editor-bundle`). Node and npm exist only inside the throw-away build container and the audit; the",
    "server image and the servers contain no Node. `static/htmx.min.js` (htmx 2.0.4, MIT) is a vendored single file with a checksum, see",
    "`static/htmx.min.js.sha256`.", "",
    "How CVEs are watched: `make audit-js` (`npm audit` + `npm audit signatures`, also in CI every day), `renovate.json` (npm packages,",
    "7 days minimum age, no automerge), and `npm ci --ignore-scripts` (no package may run an install script).", "",
    f"## In the bundle ({len(runtime)} packages)", "",
    "| package | version | license | |", "|---|---|---|---|", *[row(n, v) for n, v in runtime], "",
    f"## Only for building ({len(build)} entries: esbuild and its platform binaries; only the one for the build machine is installed)", "",
    "| package | version | license | |", "|---|---|---|---|", *[row(n, v) for n, v in build], "",
]
text = "\n".join(out)
target = root / "docs/js-dependencies.md"
if "--check" in sys.argv:
    sys.exit(0 if target.exists() and target.read_text() == text else 1)
target.write_text(text)
print(f"wrote {target.relative_to(root)}: {len(runtime)} runtime, {len(build)} build packages")
